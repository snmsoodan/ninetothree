// Turns the paired .sql files into a TypeScript module.
//
// The app runs migrations on first use, and a serverless deploy has no
// migrations directory to read: the bundle is the filesystem. Inlining the SQL
// is what makes `migrateUp` work there, and it removes `readdirSync` from the
// request path entirely.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import prettier from "prettier";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const dir = join(root, "migrations");
const out = join(root, "src", "migrations.generated.ts");

const entries = readdirSync(dir);
const names = entries
  .filter((file) => file.endsWith(".up.sql"))
  .map((file) => file.slice(0, -".up.sql".length))
  .sort((a, b) => a.localeCompare(b));

for (const name of names) {
  if (!entries.includes(`${name}.down.sql`)) {
    console.error(`${name} has no .down.sql`);
    process.exit(1);
  }
}

const body = names
  .map((name) => {
    const up = readFileSync(join(dir, `${name}.up.sql`), "utf8");
    const down = readFileSync(join(dir, `${name}.down.sql`), "utf8");
    return `  {\n    name: ${JSON.stringify(name)},\n    up: ${JSON.stringify(up)},\n    down: ${JSON.stringify(down)},\n  },`;
  })
  .join("\n");

// Formatted here rather than left to `pnpm format`, because `migrations:check`
// compares this file byte for byte against a fresh run. If the two disagree,
// one of the two guards fails no matter which one you run first.
const source = `// Generated by scripts/generate-migrations.mjs. Do not edit.
import type { Migration } from "./migrate";

export const MIGRATIONS: Migration[] = [
${body}
];
`;

writeFileSync(out, await prettier.format(source, { filepath: out }));

console.log(`wrote ${names.length} migrations to src/migrations.generated.ts`);
