#!/usr/bin/env node
/**
 * Writes packages/content/src/registry.ts from the packs directory.
 *
 * The registry is the only list of packs the app can see, so a pack that is
 * not in it is a pack no parent will ever read. Generating it means adding a
 * pack is one file, not two. `--check` fails when the file has drifted, which
 * is what CI runs.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const packsDir = join(root, "packages", "content", "packs");
const target = join(root, "packages", "content", "src", "registry.ts");

const KIND_ORDER = ["pregnancy", "postpartum", "infant", "toddler", "event"];

const files = readdirSync(packsDir)
  .filter((file) => file.endsWith(".json"))
  .sort();

const entries = files.map((file) => {
  const data = JSON.parse(readFileSync(join(packsDir, file), "utf8"));
  const kind = String(data.kind);
  const stageIndex = Number(data.stageIndex);
  const rank = KIND_ORDER.indexOf(kind);
  return {
    file,
    id: String(data.id),
    kind,
    stageIndex,
    rank: rank === -1 ? KIND_ORDER.length : rank,
  };
});

entries.sort(
  (a, b) =>
    a.rank - b.rank ||
    a.stageIndex - b.stageIndex ||
    a.file.localeCompare(b.file),
);

/** `pregnancy-w8.json` → `pregnancyW8` */
function identifier(file) {
  const base = file.replace(/\.json$/, "");
  return base.replace(/-([a-z0-9])/g, (_, char) => char.toUpperCase());
}

const imports = entries
  .map((entry) => `import ${identifier(entry.file)} from "../packs/${entry.file}";`)
  .join("\n");

const list = entries.map((entry) => `  ${identifier(entry.file)},`).join("\n");

const output = `import { assertValidPacks } from "./loader";
import type { StagePack } from "./schema";

${imports}

/**
 * Every pack, validated at module load. A broken pack fails the build
 * rather than reaching a parent at 3am.
 *
 * Generated by scripts/gen-registry.mjs. Do not edit by hand — run
 * \`pnpm content:registry\` after adding or removing a pack.
 */
export const PACKS: StagePack[] = assertValidPacks([
${list}
]);

export const PACKS_BY_ID: ReadonlyMap<string, StagePack> = new Map(
  PACKS.map((pack) => [pack.id, pack]),
);

export function getPack(id: string): StagePack | undefined {
  return PACKS_BY_ID.get(id);
}
`;

const check = process.argv.includes("--check");

if (check) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {
    console.error("✗ packages/content/src/registry.ts is missing");
    process.exit(1);
  }
  if (current !== output) {
    const registered = new Set(
      [...current.matchAll(/from "\.\.\/packs\/([^"]+)"/g)].map((m) => m[1]),
    );
    const missing = entries.filter((e) => !registered.has(e.file));
    const extra = [...registered].filter(
      (file) => !entries.some((e) => e.file === file),
    );
    console.error("✗ packages/content/src/registry.ts is out of date");
    for (const entry of missing) {
      console.error(`    not registered: ${entry.file} (${entry.id})`);
    }
    for (const file of extra) {
      console.error(`    registered but missing: ${file}`);
    }
    console.error("\n  Run `pnpm content:registry` to fix it.");
    process.exit(1);
  }
  console.log(`✓ registry lists all ${String(entries.length)} packs`);
} else {
  writeFileSync(target, output);
  console.log(`✓ wrote registry.ts with ${String(entries.length)} packs`);
}
