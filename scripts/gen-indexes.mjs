#!/usr/bin/env node
/**
 * Writes the lookup tables the app can afford to ship.
 *
 * `registry.ts` carries every word of all the packs. That is right for the
 * week page, which is rendered on the server, and wrong for everything else:
 * the dashboard needs to know which week it is, not what week 12 said about
 * nausea. So the rest of the app reads projections generated here, and the
 * full text stays behind the one route that renders it.
 *
 * Separate files, not one, so a bundler that fails to shake an unused
 * export cannot quietly put all of them in every chunk.
 *
 * The search index is the exception: it is the whole corpus, so it is a
 * static file the search page fetches rather than a module every route
 * parses.
 *
 * `--check` fails when a file has drifted, which is what CI runs.
 *
 * The types in `search.ts` are stripped by Node itself, which needs 22.18
 * or newer. That is the floor in the root package.json.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { buildIndex } from "../packages/content/src/search.ts";

const root = join(import.meta.dirname, "..");
const packsDir = join(root, "packages", "content", "packs");
const linksDir = join(root, "packages", "content", "links");
const srcDir = join(root, "packages", "content", "src");
const publicDir = join(root, "apps", "web", "public");

const HEADER = `// Generated by scripts/gen-indexes.mjs — do not edit by hand.
// Run \`pnpm content:indexes\` after changing a pack, or
// \`pnpm content:indexes:check\` to see what drifted.
`;

const files = readdirSync(packsDir)
  .filter((file) => file.endsWith(".json"))
  .sort();

const KIND_ORDER = ["pregnancy", "postpartum", "infant", "toddler", "event"];

// The same order `registry.ts` uses, so a list built from the index reads in
// the same order as a list built from the packs themselves.
const packs = files
  .map((file) => JSON.parse(readFileSync(join(packsDir, file), "utf8")))
  .sort((a, b) => {
    const rank = (pack) => {
      const at = KIND_ORDER.indexOf(pack.kind);
      return at === -1 ? KIND_ORDER.length : at;
    };
    return rank(a) - rank(b) || a.stageIndex - b.stageIndex;
  });

/** One line per record keeps the diff readable when a single pack changes. */
const record = (entry) => JSON.stringify(entry);

// --- pack-index.ts -------------------------------------------------------
// What the dashboard, shelf, history, safety and email pages need to know
// about a stage without knowing what is in it.
const packIndex = packs.map((pack) => ({
  id: pack.id,
  kind: pack.kind,
  stageIndex: pack.stageIndex,
  stageUnit: pack.stageUnit,
  title: pack.title,
  ...(pack.subtitle ? { subtitle: pack.subtitle } : {}),
  coreActionIds: pack.coreActions.map((action) => action.id),
  redFlags: pack.redFlags,
  appointments: pack.appointments ?? [],
}));

const packFile = `${HEADER}
import type { Appointment, RedFlag, StageKind, StageUnit } from "./schema";

/**
 * A stage, minus its prose.
 *
 * Every field here is something a screen other than the week page renders:
 * the title on the dashboard card, the red flags on the safety page, the
 * appointments on the dashboard and in the email.
 */
export interface PackIndexEntry {
  id: string;
  kind: StageKind;
  stageIndex: number;
  stageUnit: StageUnit;
  title: string;
  subtitle?: string;
  /** The ids of this stage's steps, in the order the week page shows them. */
  coreActionIds: string[];
  redFlags: RedFlag[];
  appointments: Appointment[];
}

export const PACK_INDEX: PackIndexEntry[] = [
${packIndex.map((entry) => `  ${record(entry)},`).join("\n")}
];

/** The pack for an id, or nothing when it has been retired. */
export function findPackIndex(
  id: string,
  index: readonly PackIndexEntry[] = PACK_INDEX,
): PackIndexEntry | undefined {
  return index.find((entry) => entry.id === id);
}

/**
 * The last pack at or before a stage.
 *
 * This is what "which week am I in?" means: a parent at 37 weeks in a guide
 * that stops at 36 is in the week 36 pack, not in nothing. The index is sorted
 * by kind and then by stage, so the first pack past the stage ends the search.
 */
export function findPackAtOrBefore(
  kind: StageKind,
  stageIndex: number,
  index: readonly PackIndexEntry[] = PACK_INDEX,
): PackIndexEntry | undefined {
  let found: PackIndexEntry | undefined;
  for (const entry of index) {
    if (entry.kind !== kind) continue;
    if (entry.stageIndex > stageIndex) break;
    found = entry;
  }
  return found;
}

/** The next pack of the same kind, for "look ahead". */
export function nextPackIndex(
  current: PackIndexEntry,
  index: readonly PackIndexEntry[] = PACK_INDEX,
): PackIndexEntry | undefined {
  const sameKind = index.filter((entry) => entry.kind === current.kind);
  const at = sameKind.findIndex((entry) => entry.id === current.id);
  return at === -1 ? undefined : sameKind[at + 1];
}

/** The previous pack of the same kind, for "last week". */
export function previousPackIndex(
  current: PackIndexEntry,
  index: readonly PackIndexEntry[] = PACK_INDEX,
): PackIndexEntry | undefined {
  const sameKind = index.filter((entry) => entry.kind === current.kind);
  const at = sameKind.findIndex((entry) => entry.id === current.id);
  return at <= 0 ? undefined : sameKind[at - 1];
}
`;

// --- stage-index.ts ------------------------------------------------------
// "Which stage am I in?" — the one question the week signpost and the paywall
// gate ask, and it needs nothing but the mapping.
const stageIndex = packs.map((pack) => ({
  id: pack.id,
  kind: pack.kind,
  stageIndex: pack.stageIndex,
}));

const stageFile = `${HEADER}
import type { StageKind } from "./schema";

/**
 * A stage and the pack that holds it.
 *
 * Small enough that the paywall gate can carry it, which matters: the gate
 * decides whether to show a week, so it cannot be the reason the week page
 * loads the whole guide.
 */
export interface StageIndexEntry {
  id: string;
  kind: StageKind;
  stageIndex: number;
}

export const STAGE_INDEX: StageIndexEntry[] = [
${stageIndex.map((entry) => `  ${record(entry)},`).join("\n")}
];

/** The pack for a stage, or nothing when that stage is not written yet. */
export function findStageIndex(
  kind: StageKind,
  stageIndex: number,
  index: readonly StageIndexEntry[] = STAGE_INDEX,
): StageIndexEntry | undefined {
  return index.find((entry) => entry.kind === kind && entry.stageIndex === stageIndex);
}

/**
 * The last pack at or before a stage.
 *
 * This is what "which week am I in?" means: a parent at 37 weeks in a guide
 * that stops at 36 is in the week 36 pack, not in nothing.
 */
export function findStageAtOrBefore(
  kind: StageKind,
  stageIndex: number,
  index: readonly StageIndexEntry[] = STAGE_INDEX,
): StageIndexEntry | undefined {
  let found: StageIndexEntry | undefined;
  for (const entry of index) {
    if (entry.kind !== kind) continue;
    if (entry.stageIndex > stageIndex) break;
    found = entry;
  }
  return found;
}

/** The next pack of the same kind, for "next week". */
export function nextStage(
  current: StageIndexEntry,
  index: readonly StageIndexEntry[] = STAGE_INDEX,
): StageIndexEntry | undefined {
  const sameKind = index.filter((entry) => entry.kind === current.kind);
  const at = sameKind.findIndex((entry) => entry.id === current.id);
  return at === -1 ? undefined : sameKind[at + 1];
}

/** The previous pack of the same kind, for "last week". */
export function previousStage(
  current: StageIndexEntry,
  index: readonly StageIndexEntry[] = STAGE_INDEX,
): StageIndexEntry | undefined {
  const sameKind = index.filter((entry) => entry.kind === current.kind);
  const at = sameKind.findIndex((entry) => entry.id === current.id);
  return at <= 0 ? undefined : sameKind[at - 1];
}
`;

// --- action-index.ts -----------------------------------------------------
// "Which stage was that step in, what was it called, and what were the
// choices?" — the question a pin, a history row, an email link and the shelf
// all ask. The shelf shows the step's reason and its options, so those are
// here too; nothing else is, because nothing else is ever read.
const actionIndex = {};
for (const pack of packs) {
  // Persona actions are pinned and shown in history exactly like the parent's,
  // so they resolve through the same index. The pack stays the stage they
  // belong to.
  const actions = [
    ...pack.coreActions,
    ...(pack.personas ?? []).flatMap((view) => view.actions),
  ];
  for (const action of actions) {
    actionIndex[action.id] = {
      id: action.id,
      title: action.title,
      packId: pack.id,
      packTitle: pack.title,
      why: action.why,
      options: (action.options ?? []).map((option) => ({
        id: option.id,
        label: option.label,
        ...(option.url ? { url: option.url } : {}),
      })),
    };
  }
}

const actionFile = `${HEADER}
/**
 * A step, reduced to what a list of steps shows.
 *
 * A pin stores an id and nothing else, because a title copied into local
 * storage goes stale the day content changes. This is what turns that id
 * back into a line of text, a reason, and the choices underneath it.
 */
export interface ActionIndexOption {
  id: string;
  label: string;
  url?: string;
}

export interface ActionIndexEntry {
  id: string;
  title: string;
  packId: string;
  packTitle: string;
  why: string;
  options: ActionIndexOption[];
}

export const ACTION_INDEX: Record<string, ActionIndexEntry> = {
${Object.values(actionIndex)
  .map((entry) => `  ${JSON.stringify(entry.id)}: ${record(entry)},`)
  .join("\n")}
};

/** A step by id, or nothing when it has been retired. */
export function findIndexedAction(
  id: string,
  index: Record<string, ActionIndexEntry> = ACTION_INDEX,
): ActionIndexEntry | undefined {
  return index[id];
}
`;

// --- rule-index.ts -------------------------------------------------------
// The settings page answers "why am I not seeing this?" across the whole
// guide, so it needs exactly the fields the rules read — and no others.
const ruleIndex = packs.map((pack) => ({
  id: pack.id,
  kind: pack.kind,
  stageIndex: pack.stageIndex,
  title: pack.title,
  ...(pack.subtitle ? { subtitle: pack.subtitle } : {}),
  redFlags: pack.redFlags ?? [],
  actions: pack.coreActions.map((action) => ({
    id: action.id,
    domain: action.domain,
    title: action.title,
    why: action.why,
    options: (action.options ?? []).map((option) => ({
      id: option.id,
      label: option.label,
      ...(option.detail ? { detail: option.detail } : {}),
      cost: option.cost,
    })),
  })),
}));

const ruleFile = `${HEADER}
import type { Cost, Domain, RedFlag, StageKind } from "./schema";

export interface RuleIndexOption {
  id: string;
  label: string;
  detail?: string;
  cost?: Cost;
}

/**
 * The fields the personalization rules actually read.
 *
 * \`domain\`, \`title\` and \`why\` are read by the hide rules; \`cost\`, \`label\` and
 * \`detail\` by the option rules. Nothing else is here, because nothing else
 * changes what a parent sees.
 */
export interface RuleIndexAction {
  id: string;
  domain: Domain;
  title: string;
  why: string;
  options: RuleIndexOption[];
}

/**
 * A pack, reduced to what the rules read and what the weekly email says.
 *
 * The email needs the subtitle and the first red flag as well as the steps,
 * because those are the two lines it opens with. Carrying them here keeps the
 * email off the full guide.
 */
export interface RuleIndexPack {
  id: string;
  kind: StageKind;
  stageIndex: number;
  title: string;
  subtitle?: string;
  redFlags: RedFlag[];
  actions: RuleIndexAction[];
}

export const RULE_INDEX: RuleIndexPack[] = [
${ruleIndex.map((entry) => `  ${record(entry)},`).join("\n")}
];

/** The pack for an id, or nothing when it has been retired. */
export function findRulePack(
  id: string,
  index: readonly RuleIndexPack[] = RULE_INDEX,
): RuleIndexPack | undefined {
  return index.find((entry) => entry.id === id);
}

/**
 * The last pack at or before a stage.
 *
 * Same answer as findPackAtOrBefore, over the rule projection: a parent at 37
 * weeks in a guide that stops at 36 is in the week 36 pack.
 */
export function findRulePackAtOrBefore(
  kind: StageKind,
  stageIndex: number,
  index: readonly RuleIndexPack[] = RULE_INDEX,
): RuleIndexPack | undefined {
  let found: RuleIndexPack | undefined;
  for (const entry of index) {
    if (entry.kind !== kind) continue;
    if (entry.stageIndex > stageIndex) break;
    found = entry;
  }
  return found;
}
`;

// --- search-index.json ---------------------------------------------------
// Every step, week and link as a search document. It is the whole corpus, so
// it is a static file the search page fetches after it paints, not a module
// every route pays to parse.
//
// The link files are listed rather than globbed because their order is part
// of the index: `link-registry.ts` puts the authoritative sources first so a
// tie between two results breaks towards the citation.
const LINK_FILES = ["authoritative", "apps", "books", "community", "extra", "gear", "services"];

const found = readdirSync(linksDir)
  .filter((file) => file.endsWith(".json"))
  .map((file) => file.replace(/\.json$/, ""))
  .sort();
const expected = [...LINK_FILES].sort();
if (found.join(",") !== expected.join(",")) {
  console.error(`Link files changed: found ${found.join(", ")}; generator knows ${expected.join(", ")}.`);
  console.error(`Add the new file to LINK_FILES in the right order: ${LINK_FILES.join(", ")}.`);
  process.exit(1);
}

const links = LINK_FILES.flatMap((name) =>
  JSON.parse(readFileSync(join(linksDir, `${name}.json`), "utf8")),
);

// The JSON on disk is the pre-parse shape: `options` and `alsoKnow` are
// optional there and default to empty in the schema, which is the shape the
// app searches. Fill them in so the file matches what the app would build.
const searchDocs = buildIndex(
  packs.map((pack) => ({
    ...pack,
    coreActions: pack.coreActions.map((action) => ({ ...action, options: action.options ?? [] })),
    alsoKnow: pack.alsoKnow ?? [],
  })),
  links,
);

// One document per line, so a content change is a readable diff rather than
// a whole file replaced. Prettier ignores this file for the same reason.
const searchJson = `[\n${searchDocs.map((doc) => JSON.stringify(doc)).join(",\n")}\n]\n`;

const outputs = [
  [srcDir, "pack-index.ts", packFile],
  [srcDir, "stage-index.ts", stageFile],
  [srcDir, "action-index.ts", actionFile],
  [srcDir, "rule-index.ts", ruleFile],
  [publicDir, "search-index.json", searchJson],
];

if (process.argv.includes("--check")) {
  const drifted = outputs.filter(([dir, name, body]) => {
    try {
      return readFileSync(join(dir, name), "utf8") !== body;
    } catch {
      return true;
    }
  });
  if (drifted.length > 0) {
    console.error(`Indexes are stale: ${drifted.map(([, name]) => name).join(", ")}`);
    console.error("Run `pnpm content:indexes` and commit the result.");
    process.exit(1);
  }
  console.log(`Indexes are current (${packs.length} packs, ${searchDocs.length} search documents).`);
} else {
  for (const [dir, name, body] of outputs) writeFileSync(join(dir, name), body);
  const bytes = outputs.reduce((total, [, , body]) => total + Buffer.byteLength(body), 0);
  console.log(`Wrote ${outputs.length} index files from ${packs.length} packs (${bytes} B).`);
}
