#!/usr/bin/env node
/**
 * Writes the three lookup tables the app can afford to ship.
 *
 * `registry.ts` carries every word of all the packs. That is right for the
 * week page, which is rendered on the server, and wrong for everything else:
 * the dashboard needs to know which week it is, not what week 12 said about
 * nausea. So the rest of the app reads projections generated here, and the
 * full text stays behind the one route that renders it.
 *
 * Three files, not one, so a bundler that fails to shake an unused export
 * cannot quietly put all of them in every chunk.
 *
 * `--check` fails when a file has drifted, which is what CI runs.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const packsDir = join(root, "packages", "content", "packs");
const srcDir = join(root, "packages", "content", "src");

const HEADER = `// Generated by scripts/gen-indexes.mjs — do not edit by hand.
// Run \`pnpm content:indexes\` after changing a pack, or
// \`pnpm content:indexes:check\` to see what drifted.
`;

const files = readdirSync(packsDir)
  .filter((file) => file.endsWith(".json"))
  .sort();

const KIND_ORDER = ["pregnancy", "postpartum", "infant", "toddler", "event"];

// The same order `registry.ts` uses, so a list built from the index reads in
// the same order as a list built from the packs themselves.
const packs = files
  .map((file) => JSON.parse(readFileSync(join(packsDir, file), "utf8")))
  .sort((a, b) => {
    const rank = (pack) => {
      const at = KIND_ORDER.indexOf(pack.kind);
      return at === -1 ? KIND_ORDER.length : at;
    };
    return rank(a) - rank(b) || a.stageIndex - b.stageIndex;
  });

/** One line per record keeps the diff readable when a single pack changes. */
const record = (entry) => JSON.stringify(entry);

// --- pack-index.ts -------------------------------------------------------
// What the dashboard, shelf, history, safety and email pages need to know
// about a stage without knowing what is in it.
const packIndex = packs.map((pack) => ({
  id: pack.id,
  kind: pack.kind,
  stageIndex: pack.stageIndex,
  stageUnit: pack.stageUnit,
  title: pack.title,
  ...(pack.subtitle ? { subtitle: pack.subtitle } : {}),
  coreActionIds: pack.coreActions.map((action) => action.id),
  redFlags: pack.redFlags,
  appointments: pack.appointments ?? [],
}));

const packFile = `${HEADER}
import type { Appointment, RedFlag, StageKind, StageUnit } from "./schema";

/**
 * A stage, minus its prose.
 *
 * Every field here is something a screen other than the week page renders:
 * the title on the dashboard card, the red flags on the safety page, the
 * appointments on the dashboard and in the email.
 */
export interface PackIndexEntry {
  id: string;
  kind: StageKind;
  stageIndex: number;
  stageUnit: StageUnit;
  title: string;
  subtitle?: string;
  /** The ids of this stage's steps, in the order the week page shows them. */
  coreActionIds: string[];
  redFlags: RedFlag[];
  appointments: Appointment[];
}

export const PACK_INDEX: PackIndexEntry[] = [
${packIndex.map((entry) => `  ${record(entry)},`).join("\n")}
];
`;

// --- stage-index.ts ------------------------------------------------------
// "Which stage am I in?" — the one question the week signpost and the paywall
// gate ask, and it needs nothing but the mapping.
const stageIndex = packs.map((pack) => ({
  id: pack.id,
  kind: pack.kind,
  stageIndex: pack.stageIndex,
}));

const stageFile = `${HEADER}
import type { StageKind } from "./schema";

/**
 * A stage and the pack that holds it.
 *
 * Small enough that the paywall gate can carry it, which matters: the gate
 * decides whether to show a week, so it cannot be the reason the week page
 * loads the whole guide.
 */
export interface StageIndexEntry {
  id: string;
  kind: StageKind;
  stageIndex: number;
}

export const STAGE_INDEX: StageIndexEntry[] = [
${stageIndex.map((entry) => `  ${record(entry)},`).join("\n")}
];

/** The pack for a stage, or nothing when that stage is not written yet. */
export function findStageIndex(
  kind: StageKind,
  stageIndex: number,
  index: readonly StageIndexEntry[] = STAGE_INDEX,
): StageIndexEntry | undefined {
  return index.find((entry) => entry.kind === kind && entry.stageIndex === stageIndex);
}
`;

// --- action-index.ts -----------------------------------------------------
// "Which stage was that step in, and what was it called?" — the only
// question a pin, a history row or an email link asks.
const actionIndex = {};
for (const pack of packs) {
  for (const action of pack.coreActions) {
    actionIndex[action.id] = {
      id: action.id,
      title: action.title,
      packId: pack.id,
      packTitle: pack.title,
    };
  }
}

const actionFile = `${HEADER}
/**
 * A step, reduced to where it lives.
 *
 * A pin stores an id and nothing else, because a title copied into local
 * storage goes stale the day content changes. This is what turns that id
 * back into a line of text.
 */
export interface ActionIndexEntry {
  id: string;
  title: string;
  packId: string;
  packTitle: string;
}

export const ACTION_INDEX: Record<string, ActionIndexEntry> = {
${Object.values(actionIndex)
  .map((entry) => `  ${JSON.stringify(entry.id)}: ${record(entry)},`)
  .join("\n")}
};
`;

// --- rule-index.ts -------------------------------------------------------
// The settings page answers "why am I not seeing this?" across the whole
// guide, so it needs exactly the fields the rules read — and no others.
const ruleIndex = packs.map((pack) => ({
  id: pack.id,
  title: pack.title,
  actions: pack.coreActions.map((action) => ({
    id: action.id,
    domain: action.domain,
    title: action.title,
    why: action.why,
    options: (action.options ?? []).map((option) => ({
      id: option.id,
      label: option.label,
      ...(option.detail ? { detail: option.detail } : {}),
      cost: option.cost,
    })),
  })),
}));

const ruleFile = `${HEADER}
import type { Cost, Domain } from "./schema";

export interface RuleIndexOption {
  id: string;
  label: string;
  detail?: string;
  cost?: Cost;
}

/**
 * The fields the personalization rules actually read.
 *
 * \`domain\`, \`title\` and \`why\` are read by the hide rules; \`cost\`, \`label\` and
 * \`detail\` by the option rules. Nothing else is here, because nothing else
 * changes what a parent sees.
 */
export interface RuleIndexAction {
  id: string;
  domain: Domain;
  title: string;
  why: string;
  options: RuleIndexOption[];
}

export interface RuleIndexPack {
  id: string;
  title: string;
  actions: RuleIndexAction[];
}

export const RULE_INDEX: RuleIndexPack[] = [
${ruleIndex.map((entry) => `  ${record(entry)},`).join("\n")}
];
`;

const outputs = [
  ["pack-index.ts", packFile],
  ["stage-index.ts", stageFile],
  ["action-index.ts", actionFile],
  ["rule-index.ts", ruleFile],
];

if (process.argv.includes("--check")) {
  const drifted = outputs.filter(([name, body]) => {
    try {
      return readFileSync(join(srcDir, name), "utf8") !== body;
    } catch {
      return true;
    }
  });
  if (drifted.length > 0) {
    console.error(`Indexes are stale: ${drifted.map(([name]) => name).join(", ")}`);
    console.error("Run `pnpm content:indexes` and commit the result.");
    process.exit(1);
  }
  console.log(`Indexes are current (${packs.length} packs).`);
} else {
  for (const [name, body] of outputs) writeFileSync(join(srcDir, name), body);
  const bytes = outputs.reduce((total, [, body]) => total + Buffer.byteLength(body), 0);
  console.log(`Wrote ${outputs.length} index files from ${packs.length} packs (${bytes} B).`);
}
